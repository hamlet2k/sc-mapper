// Generates the art of the device-specific built-in templates from the procedural models in scripts/devices/*.mjs (original
// holographic wireframes, no vendor artwork). Run by scripts/ensure-data.mjs; quick and deterministic. Writes (gitignored):
//   src/lib/deviceArt/<id>.ts      geometry: canvas size, control anchors and glow outlines (small; used to lay out the callouts)
//   src/lib/deviceArt/<id>.svg.ts  the picture as a data: URL (large; its own chunk, loaded only when the template is shown)
//   src/lib/deviceArt/index.ts     geometry of every device + a lazy loader per picture
// `node scripts/gen-device-art.mjs [id ...] [--svg dir]` also writes standalone SVGs for previews.
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';

export const DEVICES = [
  'tm-warthog-stick', 'tm-warthog-throttle', 'tm-t16000m', 'tm-twcs',
  'vkb-gladiator-scg', 'vkb-gunfighter-mcg', 'vkb-stecs',
  'virpil-alpha-prime', 'virpil-vmax-prime',
  'winctrl-carrierace', 'winctrl-viperace', 'winctrl-orion', 'winctrl-ursa-combat',
  'moza-ab6', 'moza-mtp', 'moza-mtq',
  'logitech-x56-stick', 'logitech-x56-throttle',
];
const args = process.argv.slice(2);
const svgDir = args.includes('--svg') ? args[args.indexOf('--svg') + 1] : null;
const only = args.filter((a, i) => !a.startsWith('--') && args[i - 1] !== '--svg');
const outDir = new URL('../src/lib/deviceArt/', import.meta.url);
mkdirSync(outDir, { recursive: true });
const isMain = import.meta.url === `file://${process.argv[1]}`;
const head = (id) => `// Generated by scripts/gen-device-art.mjs from scripts/devices/${id}.mjs: do not edit by hand. Original holographic wireframe art (no vendor artwork).\n`;
/** compact data: URL (quotes swapped, only the characters that break a URL escaped): much smaller than encodeURIComponent */
const svgUrl = (svg) => {
  if (svg.includes("'")) throw new Error('device art: single quotes in the SVG');
  return `data:image/svg+xml,${svg.replace(/"/g, "'").replace(/[%#<>{}|\\^`\n\r]/g, (c) => encodeURIComponent(c))}`;
};
const camel = (id) => id.replace(/-(\w)/g, (_, c) => c.toUpperCase()).replace(/^\d/, (d) => `d${d}`);
const built = DEVICES.filter((id) => existsSync(new URL(`./devices/${id}.mjs`, import.meta.url)));
for (const id of built) {
  if (isMain && only.length && !only.includes(id)) continue;
  const { default: build } = await import(`./devices/${id}.mjs`);
  const a = build();
  writeFileSync(new URL(`${id}.ts`, outDir), `${head(id)}import type { DeviceArt } from '../deviceArtTypes';
const art: DeviceArt = ${JSON.stringify({ w: a.w, h: a.h, anchors: a.anchors, regions: a.regions, inputRegions: a.inputRegions })};
export default art;
`);
  writeFileSync(new URL(`${id}.svg.ts`, outDir), `${head(id)}export default ${JSON.stringify(svgUrl(a.svg))};\n`);
  if (svgDir) { mkdirSync(svgDir, { recursive: true }); writeFileSync(`${svgDir}/${id}.svg`, a.svg); }
  if (isMain) console.log(`[device art] ${id}: svg ${a.svg.length} bytes, ${Object.keys(a.anchors).length} anchors`);
}
writeFileSync(new URL('index.ts', outDir), `// Generated by scripts/gen-device-art.mjs: geometry of every device template picture and a lazy loader for each picture.
import type { DeviceArt } from '../deviceArtTypes';
${built.map((id) => `import ${camel(id)} from './${id}';`).join('\n')}
export const DEVICE_ART: Record<string, DeviceArt> = { ${built.map((id) => `'${id}': ${camel(id)}`).join(', ')} };
/** the picture (data: URL) of a device template: each in its own chunk */
export const DEVICE_SVG: Record<string, () => Promise<string>> = {
${built.map((id) => `  '${id}': () => import('./${id}.svg').then((m) => m.default),`).join('\n')}
};
`);
